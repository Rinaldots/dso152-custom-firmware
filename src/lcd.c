void lcd_text(unsigned x, unsigned y, const char *s, uint16_t fg, uint16_t bg, unsigned scale)
{
    for (; *s; s++, x += 6u * scale) {
        unsigned ch = (unsigned char)*s;
        if (ch < 32u || ch > 126u) ch = '?';
        const uint8_t *g = FONT5X7[ch - 32u];
        lcd_window(x, y, x + 6u * scale - 1u, y + 8u * scale - 1u);
        for (unsigned c = 0; c < 6u * scale; c++) {        /* X por fora */
            unsigned col = c / scale;
            for (unsigned r = 8u * scale; r-- > 0u; ) {     /* Y de baixo para cima */
                unsigned row = r / scale;
                int on = col < 5u && row < 7u && ((g[col] >> row) & 1u);
                lcd_put(on ? fg : bg);
            }
        }
    }
}
