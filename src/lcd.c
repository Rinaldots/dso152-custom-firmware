/*
 * lcd.c — driver do ST7789 do DSO152, igual ao firmware original:
 * reset em PA8 (1, 0 por 20 ms, 1), sleep out (0x11) + 120 ms e a mesma
 * sequencia de registradores, MADCTL = 00. A conversao das coordenadas
 * logicas para CASET/RASET esta em lcd_window() (ver lcd.h).
 */
#include <stdint.h>
#include "ch32f103.h"
#include "lcd.h"

void delay_ms(uint32_t ms);

#define LCD_RD (1u << 15)

static void lcd_cmd(uint16_t c)
{
    GPIOC->BRR = LCD_RS;
    GPIOB->ODR = c;
    GPIOC->BRR = LCD_WR;
    GPIOC->BSRR = LCD_WR;
}

static void lcd_data(uint16_t d)
{
    GPIOC->BSRR = LCD_RS;
    lcd_put(d);
}

/* {comando, n de parametros, parametros...}, termina em 0xFF */
static const uint8_t INIT_SEQ[] = {
    0x36, 1,  0x00,                         /* MADCTL */
    0x3A, 1,  0x05,                         /* RGB565 */
    0xB2, 5,  0x0C, 0x0C, 0x00, 0x33, 0x33,
    0xB7, 1,  0x35,
    0xBB, 1,  0x28,
    0xC0, 1,  0x2C,
    0xC2, 1,  0x01,
    0xC3, 1,  0x0B,
    0xC4, 1,  0x20,
    0xC6, 1,  0x0F,
    0xD0, 2,  0xA4, 0xA1,
    0xE0, 14, 0xD0, 0x01, 0x08, 0x0F, 0x11, 0x2A, 0x36, 0x55, 0x44, 0x3A, 0x0B, 0x06, 0x11, 0x20,
    0xE1, 14, 0xD0, 0x02, 0x07, 0x0A, 0x0B, 0x18, 0x34, 0x43, 0x4A, 0x2B, 0x1B, 0x1C, 0x22, 0x1F,
    0x29, 0,                                /* display on */
    0xFF,
};

void lcd_init(void)
{
    RCC->APB2ENR |= RCC_APB2ENR_IOPAEN | RCC_APB2ENR_IOPBEN | RCC_APB2ENR_IOPCEN;

    /* PB0..PB15 saidas (precisa do JTAG desligado por causa de PB3/PB4) */
    GPIOB->CRL = 0x33333333u;
    GPIOB->CRH = 0x33333333u;
    /* RS, WR, RD em 1; CS (PA15) em 0; RST (PA8) em 1 */
    GPIOC->BSRR = LCD_RS | LCD_WR | LCD_RD;
    gpio_cfg(GPIOC, 13, GPIO_CRx_OUT_PP_50M);
    gpio_cfg(GPIOC, 14, GPIO_CRx_OUT_PP_50M);
    gpio_cfg(GPIOC, 15, GPIO_CRx_OUT_PP_50M);
    gpio_clr(GPIOA, 15);
    gpio_cfg(GPIOA, 15, GPIO_CRx_OUT_PP_50M);
    gpio_set(GPIOA, 8);
    gpio_cfg(GPIOA, 8, GPIO_CRx_OUT_PP_50M);

    delay_ms(10);
    gpio_clr(GPIOA, 8);
    delay_ms(20);
    gpio_set(GPIOA, 8);
    delay_ms(20);

    lcd_cmd(0x11);                          /* sleep out */
    delay_ms(120);
    for (const uint8_t *p = INIT_SEQ; *p != 0xFFu; ) {
        uint8_t cmd = *p++;
        uint8_t n = *p++;
        lcd_cmd(cmd);
        while (n--) lcd_data(*p++);
    }

    lcd_fill(0, 0, LCD_W, LCD_H, 0x0000);
}

void lcd_window(unsigned x0, unsigned y0, unsigned x1, unsigned y1)
{
    unsigned c0 = LCD_H - 1u - y1, c1 = LCD_H - 1u - y0;
    lcd_cmd(0x2A);                          /* coluna do controlador = 239 - Y */
    lcd_data((uint16_t)(c0 >> 8));
    lcd_data((uint16_t)(c0 & 0xFFu));
    lcd_data((uint16_t)(c1 >> 8));
    lcd_data((uint16_t)(c1 & 0xFFu));
    lcd_cmd(0x2B);                          /* linha do controlador = X */
    lcd_data((uint16_t)(x0 >> 8));
    lcd_data((uint16_t)(x0 & 0xFFu));
    lcd_data((uint16_t)(x1 >> 8));
    lcd_data((uint16_t)(x1 & 0xFFu));
    lcd_cmd(0x2C);                          /* escreve na RAM */
    GPIOC->BSRR = LCD_RS;                   /* daqui em diante: pixels */
}

void lcd_fill(unsigned x, unsigned y, unsigned w, unsigned h, uint16_t color)
{
    if (w == 0u || h == 0u) return;
    lcd_window(x, y, x + w - 1u, y + h - 1u);
    for (uint32_t n = (uint32_t)w * h; n; n--) lcd_put(color);
}

